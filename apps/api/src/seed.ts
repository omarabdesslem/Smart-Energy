import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import sharp from 'sharp';
import { pool, transaction } from './db.js';
import { sampleImage } from './sample-image.js';

const uploadDir = resolve(process.env.UPLOAD_DIR || './uploads');
const siteIds = ['13000000-0000-4000-8000-000000000001', '13000000-0000-4000-8000-000000000002', '13000000-0000-4000-8000-000000000003'];
try {
  await mkdir(uploadDir, { recursive: true });
  // The seed is additive and idempotent. Restarts never overwrite user edits.
  await transaction(async client => {
    await client.query('SELECT pg_advisory_xact_lock(1492027)');
    const sites = [
      ['Weber Residence', 'Anna Weber', 'Augsburg, Germany', 12.4],
      ['Hoffmann Residence', 'Lukas Hoffmann', 'Munich, Germany', 9.6],
      ['Westpark Logistics', 'Westpark GmbH', 'Stuttgart, Germany', 84.0],
    ];
    for (let n = 0; n < sites.length; n++) await client.query('INSERT INTO sites(id,name,customer,location,capacity_kw) VALUES($1,$2,$3,$4,$5) ON CONFLICT DO NOTHING', [siteIds[n], ...sites[n]]);
    for (let n = 0; n < 3; n++) {
      const inspectionId = `14000000-0000-4000-8000-00000000000${n + 1}`;
      const inserted = await client.query(`INSERT INTO inspections(id,site_id,title,notes,is_demo,status,checklist,created_at) VALUES($1,$2,$3,$4,true,$5,$6,now()-($7::text||' days')::interval) ON CONFLICT DO NOTHING RETURNING id`, [inspectionId, siteIds[n], ['Post-installation quality check', 'Customer handover review', 'Roof array commissioning'][n], 'Sample project for exploring the review workflow. All names, findings, and images are demonstration data.', n === 1 ? 'completed' : 'draft', JSON.stringify({ photos: true, components: n === 1, handover: n === 1 }), n]);
      if (!inserted.rowCount) continue;
      const photoId = randomUUID(), objectKey = `${photoId}.jpg`;
      await writeFile(resolve(uploadDir, objectKey), await sharp(Buffer.from(sampleImage(n % 2))).jpeg({ quality: 90 }).toBuffer());
      await client.query('INSERT INTO photos(id,inspection_id,filename,object_key,width,height,is_demo) VALUES($1,$2,$3,$4,1200,800,true)', [photoId, inspectionId, 'Sample roof illustration.jpg', objectKey]);
      if (n !== 1) {
        const findingId = randomUUID();
        await client.query(`INSERT INTO findings(id,photo_id,label,box,notes,source,score,model_version) VALUES($1,$2,$3,$4,$5,'demo',NULL,NULL)`, [findingId, photoId, n === 0 ? 'Visible damage' : 'Soiling', JSON.stringify(n === 0 ? { x: .353, y: .446, width: .057, height: .125 } : { x: .43, y: .46, width: .06, height: .08 }), 'Illustrative finding for the demo workflow. Not generated by a model.']);
      }
      await client.query("INSERT INTO audit_events(id,inspection_id,actor,action) VALUES($1,$2,'Demo setup','Created sample inspection')", [randomUUID(), inspectionId]);
    }
  });
  console.log('Sample projects ready. Existing data preserved.');
} finally { await pool.end(); }
