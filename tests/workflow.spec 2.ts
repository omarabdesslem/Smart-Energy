import { test, expect } from '@playwright/test';
import sharp from 'sharp';

test('customer project through photo review and handover', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const project = `Browser test ${Date.now()}`;
  await page.goto('/projects');
  await page.getByRole('button', { name: 'New project' }).click();
  const modal = page.getByRole('dialog');
  await modal.getByLabel('Project name').fill(project);
  await modal.getByLabel('Customer', { exact: true }).fill('Browser Test Customer');
  await modal.getByLabel('Location').fill('Augsburg, Germany');
  await modal.getByLabel('System size (kWp)').fill('12.4');
  await modal.getByRole('button', { name: 'Create project' }).click();
  await expect(modal).not.toBeVisible();
  const card = page.locator('.project-card').filter({ has: page.getByRole('heading', { name: project }) });
  await card.getByRole('button', { name: 'Start review' }).click();
  await page.getByRole('dialog').getByLabel('Assigned installer').fill('Anna Installer');
  await page.getByRole('dialog').getByRole('button', { name: 'Create inspection' }).click();
  await expect(page.getByRole('heading', { name: project })).toBeVisible();
  await expect(page.getByText('Installer: Anna Installer')).toBeVisible();
  const image = await sharp({ create: { width: 800, height: 600, channels: 3, background: '#557569' } }).png().toBuffer();
  await page.locator('#photo-upload').setInputFiles({ name: 'installation.png', mimeType: 'image/png', buffer: image });
  await expect(page.getByText('Uploaded', { exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Installation photo: installation.png' })).toBeVisible();
  await page.getByRole('button', { name: 'Draw finding', exact: true }).click();
  await page.locator('.photo-stage').scrollIntoViewIfNeeded();
  const bounds = await page.locator('.photo-stage').boundingBox();
  if (!bounds) throw new Error('Photo stage is missing');
  await page.mouse.move(bounds.x + bounds.width * .2, bounds.y + bounds.height * .2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .55, bounds.y + bounds.height * .6, { steps: 6 });
  await page.mouse.up();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('dialog').getByLabel('Observation').fill('Check panel surface at handover.');
  await page.getByRole('button', { name: 'Save finding', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Select finding 1: Visible damage' })).toBeVisible();
  await page.getByLabel('Review notes').fill('Visible damage confirmed.');
  await page.getByRole('button', { name: 'Save review', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Resolution needed' })).toBeVisible();
  await page.getByLabel('Resolution notes', { exact: true }).fill('Panel replaced and checked.');
  await page.getByRole('button', { name: 'Mark as resolved', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Issue resolved' })).toBeVisible();
  await page.getByLabel('Installation photos documented').check();
  await page.getByLabel('Components and workmanship checked').check();
  await page.getByLabel('Customer handover prepared').check();
  await page.getByRole('button', { name: 'Complete review', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Reopen', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Reopen', exact: true })).toBeVisible();
  const reportUrl = `${new URL(page.url()).pathname}/report.csv`;
  const csv = await page.request.get(`/api${reportUrl}`);
  expect(csv.ok()).toBeTruthy();
  expect(await csv.text()).toContain('Panel replaced and checked.');
  await page.getByRole('link', { name: 'Handover report', exact: true }).click();
  await expect(page.getByRole('heading', { name: project })).toBeVisible();
  await expect(page.getByText('Completed review', { exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Installation documentation: installation.png' })).toBeVisible();
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/handover-desktop.png', fullPage: true });
});

test('overview is responsive and the sample inspection opens', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'A clear view of quality.' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Recent inspections' })).toBeVisible();
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('link', { name: 'Projects', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true });
  await page.goto('/inspections/14000000-0000-4000-8000-000000000001');
  await expect(page.getByRole('heading', { name: 'Weber Residence' })).toBeVisible();
  await expect(page.getByText('Sample inspection.', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/inspection-mobile.png', fullPage: true });
});
